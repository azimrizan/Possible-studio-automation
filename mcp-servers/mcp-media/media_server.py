class MediaMockAdapter(BaseMockAdapter):
    """
    Deterministic layout compositor.
    Takes background imagery generated by AI and layers vector typography,
    brand marks, and high-contrast CTA badges without AI hallucination.
    """
    def __init__(self):
        super().__init__(is_mock_enabled=True)
        # Resumable job registry for video rendering (survives worker reconnects)
        self.jobs: Dict[str, Dict[str, Any]] = {}

    def generate_composite_svg(self, spec: Dict[str, Any]) -> str:
        aspect_ratio = spec.get("aspect_ratio", "4:5")
        if aspect_ratio == "1:1":
            width, height = 1080, 1080
        elif aspect_ratio == "9:16":
            width, height = 1080, 1920
        else: # 4:5
            width, height = 1080, 1350

        bg_url = spec.get("background_image_url", "https://images.unsplash.com/photo-1523275335684-37898b6baf30?w=1080&q=80")
        headline = spec.get("headline", "REVOLUTIONIZE YOUR WORKFLOW")
        subheadline = spec.get("subheadline", "The Next Generation Smart Intelligence Platform")
        cta_text = spec.get("cta_text", "Shop Now · Limited Stock")
        brand_name = spec.get("brand_name", "NEXUS")
        badge_text = spec.get("badge_text", "NEW LAUNCH")
        theme = spec.get("theme", "dark_titanium")
        accent_color = spec.get("accent_color", "#6366f1")

        # Color schemes based on variant theme
        if theme == "dark_titanium":
            accent = accent_color or "#6366f1"
            bg_gradient = "linear-gradient(180deg, rgba(15,23,42,0.4) 0%, rgba(15,23,42,0.85) 60%, rgba(10,15,30,0.98) 100%)"
            badge_bg = "rgba(99, 102, 241, 0.2)"
            badge_border = "rgba(129, 140, 248, 0.5)"
            badge_text_color = "#818cf8"
            headline_color = "#ffffff"
            subhead_color = "#cbd5e1"
            cta_bg = "linear-gradient(135deg, #6366f1, #4f46e5)"
            cta_text_color = "#ffffff"
        elif theme == "lifestyle_action":
            accent = "#f59e0b"
            bg_gradient = "linear-gradient(180deg, rgba(30,27,75,0.3) 0%, rgba(17,24,39,0.7) 50%, rgba(15,23,42,0.95) 100%)"
            badge_bg = "rgba(245, 158, 11, 0.2)"
            badge_border = "rgba(251, 191, 36, 0.6)"
            badge_text_color = "#fbbf24"
            headline_color = "#ffffff"
            subhead_color = "#e2e8f0"
            cta_bg = "linear-gradient(135deg, #f59e0b, #d97706)"
            cta_text_color = "#000000"
        else: # minimalist_luxury
            accent = "#10b981"
            bg_gradient = "linear-gradient(180deg, rgba(0,0,0,0.2) 0%, rgba(20,20,20,0.7) 60%, rgba(10,10,10,0.96) 100%)"
            badge_bg = "rgba(16, 185, 129, 0.15)"
            badge_border = "rgba(52, 211, 153, 0.4)"
            badge_text_color = "#34d399"
            headline_color = "#ffffff"
            subhead_color = "#94a3b8"
            cta_bg = "linear-gradient(135deg, #ffffff, #e2e8f0)"
            cta_text_color = "#0f172a"

        # XML / SVG escaped strings
        def esc(txt: str) -> str:
            return (
                txt.replace("&", "&amp;")
                .replace("<", "&lt;")
                .replace(">", "&gt;")
                .replace('"', "&quot;")
            )

        e_head = esc(headline)
        e_sub = esc(subheadline)
        e_cta = esc(cta_text)
        e_brand = esc(brand_name)
        e_badge = esc(badge_text)

        svg_content = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" width="{width}" height="{height}">
  <defs>
    <style>
      @import url('https://fonts.googleapis.com/css2?family=Plus+Jakarta+Sans:wght@400;600;700;800;900&amp;display=swap');
      .brand-title {{ font-family: 'Plus Jakarta Sans', -apple-system, sans-serif; font-weight: 800; letter-spacing: 4px; fill: #ffffff; font-size: 28px; text-transform: uppercase; }}
      .badge-text {{ font-family: 'Plus Jakarta Sans', -apple-system, sans-serif; font-weight: 700; letter-spacing: 1.5px; fill: {badge_text_color}; font-size: 18px; text-transform: uppercase; }}
      .headline-text {{ font-family: 'Plus Jakarta Sans', -apple-system, sans-serif; font-weight: 900; line-height: 1.1; fill: {headline_color}; font-size: 64px; text-transform: uppercase; }}
      .subhead-text {{ font-family: 'Plus Jakarta Sans', -apple-system, sans-serif; font-weight: 500; fill: {subhead_color}; font-size: 26px; }}
      .cta-text {{ font-family: 'Plus Jakarta Sans', -apple-system, sans-serif; font-weight: 800; letter-spacing: 1px; fill: {cta_text_color}; font-size: 24px; text-transform: uppercase; }}
    </style>
    <linearGradient id="overlayGrad" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0%" stop-color="#090d16" stop-opacity="0.35" />
      <stop offset="45%" stop-color="#090d16" stop-opacity="0.75" />
      <stop offset="100%" stop-color="#04060a" stop-opacity="0.98" />
    </linearGradient>
    <linearGradient id="ctaGrad" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0%" stop-color="{accent}" />
      <stop offset="100%" stop-color="#4338ca" />
    </linearGradient>
    <filter id="cardGlow" x="-10%" y="-10%" width="120%" height="120%">
      <feDropShadow dx="0" dy="12" stdDeviation="16" flood-color="#000000" flood-opacity="0.45"/>
    </filter>
  </defs>

  <!-- Background Imagery (AI Generated) -->
  <image href="{bg_url}" x="0" y="0" width="{width}" height="{height}" preserveAspectRatio="xMidYMid slice" />

  <!-- Deterministic Gradient Overlay for Typography Contrast -->
  <rect x="0" y="0" width="{width}" height="{height}" fill="url(#overlayGrad)" />

  <!-- Top Brand Navigation Bar -->
  <g transform="translate(60, 80)">
    <circle cx="20" cy="20" r="16" fill="{accent}" />
    <text x="50" y="27" class="brand-title">{e_brand}</text>
  </g>

  <!-- High-Impact Badge -->
  <g transform="translate(60, {height - 480})">
    <rect x="0" y="0" width="220" height="42" rx="21" fill="{badge_bg}" stroke="{badge_border}" stroke-width="1.5" />
    <text x="110" y="27" text-anchor="middle" class="badge-text">{e_badge}</text>
  </g>

  <!-- Deterministic Headline (Never distorted) -->
  <g transform="translate(60, {height - 390})">
    <text x="0" y="0" class="headline-text">{e_head}</text>
  </g>

  <!-- Subheadline -->
  <g transform="translate(60, {height - 240})">
    <text x="0" y="0" class="subhead-text">{e_sub}</text>
  </g>

  <!-- Call To Action Pill Button -->
  <g transform="translate(60, {height - 180})" filter="url(#cardGlow)">
    <rect x="0" y="0" width="380" height="76" rx="38" fill="url(#ctaGrad)" />
    <text x="190" y="47" text-anchor="middle" class="cta-text">{e_cta} →</text>
  </g>

  <!-- Framing / Safe Area Watermark Indicator -->
  <rect x="24" y="24" width="{width - 48}" height="{height - 48}" rx="24" fill="none" stroke="rgba(255,255,255,0.08)" stroke-width="2" />
</svg>"""
        return svg_content

    async def render_poster(self, spec: Dict[str, Any]) -> Dict[str, Any]:
        svg_content = self.generate_composite_svg(spec)
        # Create deterministic storage key and Data URI preview
        spec_hash = hashlib.sha256(str(spec).encode()).hexdigest()[:12]
        storage_key = f"posters/{spec.get('theme', 'variant')}_{spec_hash}.svg"
        
        # URL safe data URI for instantaneous zero-latency preview
        encoded_svg = urllib.parse.quote(svg_content)
        data_uri = f"data:image/svg+xml;utf8,{encoded_svg}"

        return {
            "status": "COMPLETED",
            "storage_key": storage_key,
            "preview_url": data_uri,
            "format": "SVG_COMPOSITED",
            "aspect_ratio": spec.get("aspect_ratio", "4:5"),
            "width": 1080,
            "height": 1350 if spec.get("aspect_ratio", "4:5") == "4:5" else (1080 if spec.get("aspect_ratio") == "1:1" else 1920),
            "layout_spec": spec,
        }

    async def render_reel(self, storyboard: list, aspect_ratio: str = "9:16", audio_track: str = "cinematic_synth_anthem", brand_name: str = "AURA") -> Dict[str, Any]:
        total_duration = sum(s.get("duration", 3.0) for s in storyboard) or 15.0
        job_hash = hashlib.sha256(str(storyboard).encode()).hexdigest()[:10]
        job_id = f"reel_job_{job_hash}"
        
        output_url = f"https://assets.possiblestudio.ai/reels/{job_id}.mp4"
        thumbnail_url = "https://images.unsplash.com/photo-1510519138195-068d82f8d515?w=1080&q=80"

        job_record = {
            "job_id": job_id,
            "status": "COMPLETED",
            "progress_percent": 100,
            "output_url": output_url,
            "thumbnail_url": thumbnail_url,
            "aspect_ratio": aspect_ratio,
            "duration_seconds": total_duration,
            "audio_track": audio_track,
            "brand_name": brand_name,
            "scenes_count": len(storyboard),
            "storyboard": storyboard,
        }
        self.jobs[job_id] = job_record
        return job_record

mock_adapter = MediaMockAdapter()

server = MCPServer(
    name="mcp-media",
    version="0.1.0",
)

async def handle_render_poster(args: Dict[str, Any], ctx: TenantContext) -> Dict[str, Any]:
    layout_spec = args.get("layout_spec", {})
    res = await mock_adapter.render_poster(layout_spec)
    res["tenant_id"] = ctx.tenant_id
    return res

async def handle_render_reel(args: Dict[str, Any], ctx: TenantContext) -> Dict[str, Any]:
    storyboard = args.get("storyboard", [])
    aspect_ratio = args.get("aspect_ratio", "9:16")
    audio_track = args.get("audio_track", "cinematic_synth_anthem")
    brand_name = args.get("brand_name", "AURA")

    res = await mock_adapter.render_reel(storyboard, aspect_ratio, audio_track, brand_name)
    res["tenant_id"] = ctx.tenant_id
    return res

async def handle_get_render_status(args: Dict[str, Any], ctx: TenantContext) -> Dict[str, Any]:
    job_id = args.get("job_id", "")
    if job_id in mock_adapter.jobs:
        job_data = dict(mock_adapter.jobs[job_id])
        job_data["tenant_id"] = ctx.tenant_id
        return job_data
    return {
        "tenant_id": ctx.tenant_id,
        "job_id": job_id,
        "status": "COMPLETED",
        "progress_percent": 100,
        "output_url": f"https://assets.possiblestudio.ai/reels/{job_id}.mp4",
        "duration_seconds": 15.0,
    }

server.register_tool(
    name="render_poster",
    description="Composites clean background art, typography, brand logo, badges, and CTA overlays deterministically.",
    handler=handle_render_poster,
    parameters_schema={
        "type": "object",
        "properties": {
            "layout_spec": {
                "type": "object",
                "properties": {
                    "headline": {"type": "string"},
                    "subheadline": {"type": "string"},
                    "cta_text": {"type": "string"},
                    "background_image_url": {"type": "string"},
                    "brand_name": {"type": "string"},
                    "theme": {"type": "string", "enum": ["dark_titanium", "lifestyle_action", "minimalist_luxury"]},
                    "aspect_ratio": {"type": "string", "enum": ["1:1", "4:5", "9:16"]},
                    "badge_text": {"type": "string"},
                    "accent_color": {"type": "string"},
                },
                "required": ["headline"],
            }
        },
        "required": ["layout_spec"],
    },
    risk_class=RiskClass.WRITE,
    requires_approval=False,
    idempotent=True,
)

server.register_tool(
    name="render_reel",
    description="Asynchronously renders 9:16 reel with multi-scene storyboard, dynamic captions, and background music.",
    handler=handle_render_reel,
    parameters_schema={
        "type": "object",
        "properties": {
            "storyboard": {
                "type": "array",
                "items": {"type": "object"},
                "description": "Sequence of scenes with visual prompts, durations, and caption overlays",
            },
            "aspect_ratio": {"type": "string", "enum": ["9:16", "1:1", "16:9"], "default": "9:16"},
            "audio_track": {"type": "string", "default": "cinematic_synth_anthem"},
            "brand_name": {"type": "string", "default": "AURA"},
        },
        "required": ["storyboard"],
    },
    risk_class=RiskClass.WRITE,
    requires_approval=False,
    idempotent=True,
)

server.register_tool(
    name="get_render_status",
    description="Queries status of media rendering job and returns output URL and progress.",
    handler=handle_get_render_status,
    parameters_schema={
        "type": "object",
        "properties": {
            "job_id": {"type": "string"},
        },
        "required": ["job_id"],
    },
    risk_class=RiskClass.READ,
    requires_approval=False,
    idempotent=True,
)

app = server.app

if __name__ == "__main__":
    import uvicorn
    port = int(os.getenv("PORT", "8104"))
    uvicorn.run(app, host="0.0.0.0", port=port)
